import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'vite';

const root = new URL('../', import.meta.url);
const major = process.argv.find((arg) => /^--v[23456]$/.test(arg))?.slice(3) ?? '1';
const version = `0.${major}.0`;
const folder = major === '1' ? 'src/lib/contract/' : `src/lib/contract/v${major}/`;
const spec = JSON.parse(readFileSync(new URL(`${folder}api-v${version}.json`, root), 'utf8'));
const definitions = JSON.parse(
  JSON.stringify(spec.components.schemas).replaceAll('#/components/schemas/', '#/$defs/'),
);
const schemaId = `urn:db-manager:api:${version}`;
const ajv = new Ajv2020({ strict: false, code: { source: true, esm: true } });
ajv.addSchema({ $id: schemaId, $defs: definitions });
const exports = Object.fromEntries(
  Object.keys(definitions).map((name) => [name, `${schemaId}#/$defs/${name}`]),
);
const cache = new URL('node_modules/.cache/', root);
mkdirSync(cache, { recursive: true });
const entry = new URL('db-manager-validators.js', cache);
writeFileSync(entry, standaloneCode(ajv, exports));
// Bundle Ajv's standalone Unicode-length helper without importing its compiler at runtime.
const built = await build({
  configFile: false,
  logLevel: 'silent',
  root: fileURLToPath(root),
  build: {
    write: false,
    emptyOutDir: false,
    target: 'es2022',
    minify: false,
    sourcemap: false,
    lib: { entry: fileURLToPath(entry), formats: ['es'], fileName: 'validators' },
    commonjsOptions: { transformMixedEsModules: true },
  },
});
const output = (Array.isArray(built) ? built[0] : built).output;
const chunks = output.filter((item) => item.type === 'chunk');
if (chunks.length !== 1 || chunks[0].imports.length !== 0) {
  throw new Error('Standalone validators must form one self-contained module.');
}
const code = `// @ts-nocheck\n// Generated by tests/generate-validators.mjs; do not edit.\n// Own generator: AGPL-3.0-only; Ajv helper: MIT, see third-party notices.\n${chunks[0].code}`;
if (/\bnew\s+Function\s*\(|\beval\s*\(/.test(code)) {
  throw new Error('Generated validators must not use dynamic code evaluation.');
}
const types = `// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by tests/generate-validators.mjs; do not edit.\nimport type { components } from './api-types';\n${Object.keys(
  definitions,
)
  .map(
    (name) =>
      `export const ${name}: (value: unknown) => value is components['schemas']['${name}'];`,
  )
  .join('\n')}\n`;
for (const [name, content] of [
  ['validators.js', code],
  ['validators.d.ts', types],
]) {
  const path = new URL(`${folder}${name}`, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`Generated ${name} is stale.`);
  } else {
    writeFileSync(path, content);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Standalone validators are current.'
    : 'Standalone validators generated.',
);
