const GROUPS: Record<Driver, string[]> = {
  sqlite: [...common, ...sqlite],
  mysql: [...common, ...mysql],
  postgresql: [...common, ...postgres],
};

it('dumps the targeted corpus', () => {
  const out = process.env.DBM_CORPUS_OUT;
  if (!out) return;
  mkdirSync(out, { recursive: true });
  for (const d of Object.keys(GROUPS) as Driver[]) {
    const pairs = GROUPS[d]
      .map((o) => ({ o, f: formatSql(o, d) }))
      .filter((p) => p.f !== null && p.f !== p.o);
    writeFileSync(join(out, `${d}.json`), JSON.stringify(pairs));
    console.log(d, GROUPS[d].length, 'statements', pairs.length, 'formatted');
  }
});
